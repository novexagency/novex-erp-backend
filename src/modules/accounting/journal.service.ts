import {
  AccountingEventType,
  JournalAuditAction,
  JournalStatus,
  Prisma,
  WorkflowDocumentType,
} from "@prisma/client";
import { prisma } from "../../lib/prisma.js";
import { assertSameTenant, requireTenantId } from "../../lib/tenantDb.js";
import { AppError } from "../../utils/AppError.js";
import type { TenantId } from "../../types/tenant.js";
import type { WorkflowOpts } from "../workflow/adapters/types.js";
import { startApprovalIfConfigured } from "../workflow/engine.service.js";
import {
  assertBalanced,
  createJournalInTx,
  resolveOpenPeriod,
  type JournalLineInput,
} from "./posting.engine.js";

export async function listJournals(
  tenantId: TenantId,
  opts?: { status?: string; eventType?: string; from?: string; to?: string }
) {
  const tid = requireTenantId(tenantId);
  return prisma.journalEntry.findMany({
    where: {
      organizationId: tid,
      ...(opts?.status ? { status: opts.status as JournalStatus } : {}),
      ...(opts?.eventType ? { eventType: opts.eventType as AccountingEventType } : {}),
      ...(opts?.from || opts?.to
        ? {
            entryDate: {
              ...(opts.from ? { gte: new Date(opts.from) } : {}),
              ...(opts.to ? { lte: new Date(opts.to) } : {}),
            },
          }
        : {}),
    },
    include: { lines: { include: { account: true } } },
    orderBy: { entryDate: "desc" },
    take: 200,
  });
}

export async function getJournal(tenantId: TenantId, id: string) {
  const tid = requireTenantId(tenantId);
  const row = await prisma.journalEntry.findUnique({
    where: { id },
    include: {
      lines: { include: { account: true }, orderBy: { lineNo: "asc" } },
      auditLogs: { orderBy: { at: "asc" } },
      period: true,
      reversesJournal: true,
      reversedByJournal: true,
    },
  });
  if (!row) throw new AppError("Journal not found", 404);
  assertSameTenant(row.organizationId, tid);
  return row;
}

export async function createManualJournal(
  tenantId: TenantId,
  data: {
    entryDate?: string;
    description?: string | null;
    lines: JournalLineInput[];
  },
  userId?: string
) {
  const tid = requireTenantId(tenantId);
  return prisma.$transaction(async (tx) =>
    createJournalInTx(tx, {
      organizationId: tid,
      eventType: AccountingEventType.MANUAL,
      entryDate: data.entryDate ? new Date(data.entryDate) : new Date(),
      description: data.description,
      sourceType: null,
      sourceId: null,
      lines: data.lines,
      autoGenerated: false,
      autoPost: false,
      userId,
    })
  );
}

export async function updateDraftJournal(
  tenantId: TenantId,
  id: string,
  data: {
    entryDate?: string;
    description?: string | null;
    lines?: JournalLineInput[];
  },
  userId?: string
) {
  const tid = requireTenantId(tenantId);

  return prisma.$transaction(async (tx) => {
    const journal = await tx.journalEntry.findUnique({ where: { id } });
    if (!journal) throw new AppError("Journal not found", 404);
    assertSameTenant(journal.organizationId, tid);
    if (journal.status !== JournalStatus.DRAFT) {
      throw new AppError("Only draft journals can be edited", 400);
    }
    if (journal.autoGenerated && journal.sourceId) {
      // Allow editing lines of auto draft for review before post
    }

    let totalDebit = Number(journal.totalDebit);
    let totalCredit = Number(journal.totalCredit);
    let periodId = journal.periodId;

    if (data.entryDate) {
      const period = await resolveOpenPeriod(tx, tid, new Date(data.entryDate));
      periodId = period.id;
    }

    if (data.lines) {
      const totals = assertBalanced(data.lines);
      totalDebit = totals.totalDebit;
      totalCredit = totals.totalCredit;
      await tx.journalLine.deleteMany({ where: { journalId: id } });
      await tx.journalLine.createMany({
        data: data.lines.map((l, i) => ({
          organizationId: tid,
          journalId: id,
          accountId: l.accountId,
          lineNo: i + 1,
          debit: new Prisma.Decimal(l.debit.toFixed(4)),
          credit: new Prisma.Decimal(l.credit.toFixed(4)),
          memo: l.memo ?? null,
        })),
      });
    }

    const updated = await tx.journalEntry.update({
      where: { id },
      data: {
        description: data.description !== undefined ? data.description : journal.description,
        entryDate: data.entryDate ? new Date(data.entryDate) : journal.entryDate,
        periodId,
        totalDebit: new Prisma.Decimal(totalDebit),
        totalCredit: new Prisma.Decimal(totalCredit),
        reviewedByUserId: userId,
        reviewedAt: new Date(),
      },
      include: { lines: { include: { account: true } } },
    });

    await tx.journalAuditLog.create({
      data: {
        organizationId: tid,
        journalId: id,
        action: JournalAuditAction.UPDATED,
        userId,
        note: "Draft updated",
      },
    });

    return updated;
  });
}

export async function postJournal(
  tenantId: TenantId,
  id: string,
  userId?: string,
  opts?: WorkflowOpts
) {
  const tid = requireTenantId(tenantId);

  const existing = await prisma.journalEntry.findUnique({
    where: { id },
    include: { lines: true },
  });
  if (!existing) throw new AppError("Journal not found", 404);
  assertSameTenant(existing.organizationId, tid);
  if (existing.status === JournalStatus.POSTED) throw new AppError("Already posted", 409);
  if (existing.status === JournalStatus.REVERSED) throw new AppError("Journal was reversed", 400);
  if (existing.status !== JournalStatus.DRAFT) throw new AppError("Only drafts can be posted", 400);

  if (!opts?.fromWorkflow) {
    const amount = existing.lines.reduce((s, l) => s + Number(l.debit), 0);
    const approval = await startApprovalIfConfigured(tid, {
      documentType: WorkflowDocumentType.MANUAL_JOURNAL,
      documentId: id,
      amount,
      submittedByUserId: userId,
    });
    if (approval) {
      return { ...existing, pendingApproval: true, approvalId: approval.id };
    }
  }

  return prisma.$transaction(async (tx) => {
    const journal = await tx.journalEntry.findUnique({
      where: { id },
      include: { lines: true },
    });
    if (!journal) throw new AppError("Journal not found", 404);
    assertSameTenant(journal.organizationId, tid);
    if (journal.status === JournalStatus.POSTED) throw new AppError("Already posted", 409);
    if (journal.status === JournalStatus.REVERSED) throw new AppError("Journal was reversed", 400);
    if (journal.status !== JournalStatus.DRAFT) throw new AppError("Only drafts can be posted", 400);

    assertBalanced(
      journal.lines.map((l) => ({
        accountId: l.accountId,
        debit: Number(l.debit),
        credit: Number(l.credit),
      }))
    );

    await resolveOpenPeriod(tx, tid, journal.entryDate);

    const updated = await tx.journalEntry.update({
      where: { id },
      data: {
        status: JournalStatus.POSTED,
        postedAt: new Date(),
        postedByUserId: userId,
        reviewedByUserId: userId,
        reviewedAt: new Date(),
      },
      include: { lines: { include: { account: true } }, period: true },
    });

    await tx.journalAuditLog.create({
      data: {
        organizationId: tid,
        journalId: id,
        action: JournalAuditAction.REVIEWED,
        userId,
        note: "Reviewed before post",
      },
    });
    await tx.journalAuditLog.create({
      data: {
        organizationId: tid,
        journalId: id,
        action: JournalAuditAction.POSTED,
        userId,
        note: "Manually posted",
      },
    });

    return updated;
  });
}

export async function reverseJournal(
  tenantId: TenantId,
  id: string,
  reason: string,
  userId?: string,
  authorized?: boolean
) {
  const tid = requireTenantId(tenantId);
  if (!authorized) throw new AppError("Journal reversal requires authorization", 403);
  if (!reason?.trim()) throw new AppError("Reversal reason required", 400);

  return prisma.$transaction(async (tx) => {
    const original = await tx.journalEntry.findUnique({
      where: { id },
      include: { lines: true, reversedByJournal: true },
    });
    if (!original) throw new AppError("Journal not found", 404);
    assertSameTenant(original.organizationId, tid);
    if (original.status !== JournalStatus.POSTED) {
      throw new AppError("Only posted journals can be reversed", 400);
    }
    if (original.reversedByJournal) throw new AppError("Already reversed", 409);

    const lines: JournalLineInput[] = original.lines.map((l) => ({
      accountId: l.accountId,
      debit: Number(l.credit),
      credit: Number(l.debit),
      memo: `Reversal of ${original.code}`,
    }));

    const reversal = await createJournalInTx(tx, {
      organizationId: tid,
      eventType: original.eventType,
      entryDate: new Date(),
      description: reason,
      sourceType: original.sourceType ? `${original.sourceType}:REV` : `MANUAL_REV`,
      sourceId: original.sourceId ?? original.id,
      sourceCode: original.sourceCode,
      lines,
      autoGenerated: false,
      autoPost: true,
      userId,
      reversesJournalId: original.id,
    });

    await tx.journalEntry.update({
      where: { id },
      data: { status: JournalStatus.REVERSED },
    });
    await tx.journalAuditLog.create({
      data: {
        organizationId: tid,
        journalId: id,
        action: JournalAuditAction.REVERSED,
        userId,
        note: reason,
      },
    });

    return { originalId: id, reversal };
  });
}

export async function rejectJournalWorkflow(
  tenantId: TenantId,
  id: string,
  reason?: string
) {
  const tid = requireTenantId(tenantId);
  const journal = await prisma.journalEntry.findUnique({ where: { id } });
  if (!journal) throw new AppError("Journal not found", 404);
  assertSameTenant(journal.organizationId, tid);
  await prisma.journalAuditLog.create({
    data: {
      organizationId: tid,
      journalId: id,
      action: JournalAuditAction.UPDATED,
      note: reason ? `Workflow rejected: ${reason}` : "Workflow rejected",
    },
  });
  return prisma.journalEntry.findUniqueOrThrow({
    where: { id },
    include: { lines: true },
  });
}
