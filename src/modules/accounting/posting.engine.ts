import {
  AccountingEventType,
  AccountingPeriodStatus,
  GlAccountStatus,
  JournalAuditAction,
  JournalStatus,
  Prisma,
} from "@prisma/client";
import { nextDocumentNumber } from "../../lib/documentNumber.js";
import { AppError } from "../../utils/AppError.js";

export type Tx = Prisma.TransactionClient;

export type JournalLineInput = {
  accountId: string;
  debit: number;
  credit: number;
  memo?: string | null;
};

export type SourcePostingContext = {
  organizationId: string;
  eventType: AccountingEventType;
  sourceType: string;
  sourceId: string;
  sourceCode?: string | null;
  entryDate?: Date;
  description?: string | null;
  /** Primary amount (invoice total, receipt amount, expense total, etc.) */
  amount: number;
  /** Optional secondary amount (COGS, inventory cost) */
  secondaryAmount?: number | null;
  /** Override cash vs bank for receipt/payment (defaults from rule) */
  cashAccountId?: string | null;
  bankAccountId?: string | null;
  useBank?: boolean;
  userId?: string | null;
};

function round4(n: number) {
  return Number(n.toFixed(4));
}

export function assertBalanced(lines: JournalLineInput[]) {
  const debit = round4(lines.reduce((s, l) => s + l.debit, 0));
  const credit = round4(lines.reduce((s, l) => s + l.credit, 0));
  if (Math.abs(debit - credit) > 0.01) {
    const difference = round4(debit - credit);
    throw new AppError(
      `Journal unbalanced: debit ${debit} != credit ${credit} (difference ${difference})`,
      400
    );
  }
  if (debit <= 0) throw new AppError("Journal must have positive amounts", 400);
  for (const l of lines) {
    if (l.debit < 0 || l.credit < 0) throw new AppError("Negative line amounts not allowed", 400);
    if (l.debit > 0 && l.credit > 0) throw new AppError("Line cannot have both debit and credit", 400);
    if (l.debit === 0 && l.credit === 0) throw new AppError("Empty journal line", 400);
  }
  return { totalDebit: debit, totalCredit: credit };
}

export async function resolveOpenPeriod(tx: Tx, organizationId: string, entryDate: Date) {
  const period = await tx.accountingPeriod.findFirst({
    where: {
      organizationId,
      startDate: { lte: entryDate },
      endDate: { gte: entryDate },
    },
  });
  if (!period) {
    throw new AppError("No accounting period covers this entry date — seed fiscal periods first", 400);
  }
  if (period.status === AccountingPeriodStatus.CLOSED) {
    throw new AppError(`Accounting period ${period.code} is closed`, 400);
  }
  if (period.status === AccountingPeriodStatus.LOCKED) {
    throw new AppError(`Accounting period ${period.code} is locked`, 400);
  }
  return period;
}

async function writeAudit(
  tx: Tx,
  organizationId: string,
  journalId: string,
  action: JournalAuditAction,
  userId?: string | null,
  note?: string | null
) {
  await tx.journalAuditLog.create({
    data: {
      organizationId,
      journalId,
      action,
      userId: userId ?? null,
      note: note ?? null,
    },
  });
}

export async function createJournalInTx(
  tx: Tx,
  args: {
    organizationId: string;
    eventType: AccountingEventType;
    entryDate: Date;
    description?: string | null;
    sourceType?: string | null;
    sourceId?: string | null;
    sourceCode?: string | null;
    lines: JournalLineInput[];
    autoGenerated?: boolean;
    autoPost?: boolean;
    userId?: string | null;
    reversesJournalId?: string | null;
  }
) {
  const { totalDebit, totalCredit } = assertBalanced(args.lines);
  const period = await resolveOpenPeriod(tx, args.organizationId, args.entryDate);

  if (args.sourceType && args.sourceId) {
    const dup = await tx.journalEntry.findUnique({
      where: {
        organizationId_sourceType_sourceId: {
          organizationId: args.organizationId,
          sourceType: args.sourceType,
          sourceId: args.sourceId,
        },
      },
    });
    if (dup) {
      throw new AppError("Journal already exists for this source document", 409);
    }
  }

  for (const line of args.lines) {
    const acc = await tx.glAccount.findFirst({
      where: {
        id: line.accountId,
        organizationId: args.organizationId,
        status: GlAccountStatus.ACTIVE,
        isPostable: true,
      },
    });
    if (!acc) throw new AppError(`GL account not found or not postable: ${line.accountId}`, 400);
  }

  const code = await nextDocumentNumber(tx, args.organizationId, "JE", "JE");
  const shouldPost = Boolean(args.autoPost);
  const status = shouldPost ? JournalStatus.POSTED : JournalStatus.DRAFT;

  const journal = await tx.journalEntry.create({
    data: {
      organizationId: args.organizationId,
      code,
      status,
      eventType: args.eventType,
      entryDate: args.entryDate,
      description: args.description,
      sourceType: args.sourceType,
      sourceId: args.sourceId,
      sourceCode: args.sourceCode,
      periodId: period.id,
      autoGenerated: Boolean(args.autoGenerated),
      autoPosted: shouldPost && Boolean(args.autoGenerated),
      totalDebit: new Prisma.Decimal(totalDebit),
      totalCredit: new Prisma.Decimal(totalCredit),
      createdByUserId: args.userId,
      postedByUserId: shouldPost ? args.userId : null,
      postedAt: shouldPost ? new Date() : null,
      reversesJournalId: args.reversesJournalId ?? null,
      lines: {
        create: args.lines.map((l, i) => ({
          organizationId: args.organizationId,
          accountId: l.accountId,
          lineNo: i + 1,
          debit: new Prisma.Decimal(round4(l.debit)),
          credit: new Prisma.Decimal(round4(l.credit)),
          memo: l.memo ?? null,
        })),
      },
    },
    include: { lines: { include: { account: true } }, period: true },
  });

  await writeAudit(
    tx,
    args.organizationId,
    journal.id,
    JournalAuditAction.CREATED,
    args.userId,
    args.autoGenerated ? "Auto-generated from source document" : "Manual journal"
  );
  if (args.autoGenerated) {
    await writeAudit(
      tx,
      args.organizationId,
      journal.id,
      JournalAuditAction.RULE_APPLIED,
      args.userId,
      `Event ${args.eventType}, autoPost=${shouldPost}`
    );
  }
  if (shouldPost) {
    await writeAudit(tx, args.organizationId, journal.id, JournalAuditAction.POSTED, args.userId, "Posted");
  }

  return journal;
}

function buildLinesFromRule(
  rule: {
    debitAccountId: string | null;
    creditAccountId: string | null;
    debitSecondaryId: string | null;
    creditSecondaryId: string | null;
  },
  amount: number,
  secondaryAmount: number | null | undefined,
  overrides?: { debitAccountId?: string | null; creditAccountId?: string | null }
): JournalLineInput[] {
  const debitId = overrides?.debitAccountId || rule.debitAccountId;
  const creditId = overrides?.creditAccountId || rule.creditAccountId;
  if (!debitId || !creditId) {
    throw new AppError("Posting rule missing debit/credit accounts", 400);
  }
  const primary = round4(amount);
  if (primary <= 0) throw new AppError("Posting amount must be positive", 400);

  const lines: JournalLineInput[] = [
    { accountId: debitId, debit: primary, credit: 0, memo: "Primary debit" },
    { accountId: creditId, debit: 0, credit: primary, memo: "Primary credit" },
  ];

  const sec = secondaryAmount != null ? round4(secondaryAmount) : 0;
  if (sec > 0) {
    if (!rule.debitSecondaryId || !rule.creditSecondaryId) {
      // Secondary amount provided but no secondary accounts — skip (sales without COGS mapping)
    } else {
      lines.push(
        { accountId: rule.debitSecondaryId, debit: sec, credit: 0, memo: "Secondary debit" },
        { accountId: rule.creditSecondaryId, debit: 0, credit: sec, memo: "Secondary credit" }
      );
    }
  }

  return lines;
}

/**
 * Generate journal for a posted source document inside the caller's transaction.
 * Requires an active posting rule. autoPost controls DRAFT vs POSTED.
 */
export async function generateForSource(tx: Tx, ctx: SourcePostingContext) {
  if (ctx.amount <= 0) throw new AppError("Source amount must be positive for journal", 400);

  const rule = await tx.accountingPostingRule.findUnique({
    where: {
      organizationId_eventType: {
        organizationId: ctx.organizationId,
        eventType: ctx.eventType,
      },
    },
  });
  if (!rule || !rule.isActive) {
    throw new AppError(
      `No active accounting posting rule for ${ctx.eventType} — seed defaults or configure rules`,
      400
    );
  }

  let debitOverride: string | null | undefined;
  let creditOverride: string | null | undefined;
  if (ctx.eventType === AccountingEventType.CUSTOMER_RECEIPT) {
    debitOverride = ctx.useBank ? ctx.bankAccountId : ctx.cashAccountId;
    // Prefer GL mapping from rule; cash/bank overrides only if we mapped treasury to GL later.
    // For now rule debit is CASH or BANK system account — keep rule unless override is a GL id.
  }
  if (ctx.eventType === AccountingEventType.SUPPLIER_PAYMENT) {
    creditOverride = ctx.useBank ? ctx.bankAccountId : ctx.cashAccountId;
  }

  // Cash/bank overrides from treasury are not GL IDs — ignore unless they match existing GL accounts
  const resolveOverride = async (id?: string | null) => {
    if (!id) return null;
    const acc = await tx.glAccount.findFirst({
      where: { id, organizationId: ctx.organizationId },
    });
    return acc?.id ?? null;
  };

  const lines = buildLinesFromRule(
    rule,
    ctx.amount,
    ctx.secondaryAmount,
    {
      debitAccountId: await resolveOverride(debitOverride),
      creditAccountId: await resolveOverride(creditOverride),
    }
  );

  return createJournalInTx(tx, {
    organizationId: ctx.organizationId,
    eventType: ctx.eventType,
    entryDate: ctx.entryDate ?? new Date(),
    description: ctx.description ?? `${ctx.eventType} ${ctx.sourceCode ?? ctx.sourceId}`,
    sourceType: ctx.sourceType,
    sourceId: ctx.sourceId,
    sourceCode: ctx.sourceCode,
    lines,
    autoGenerated: true,
    autoPost: rule.autoPost,
    userId: ctx.userId,
  });
}

/** Reverse a posted journal for a source (e.g. cancel). Creates a new posted reversing JE. */
export async function reverseJournalForSource(
  tx: Tx,
  organizationId: string,
  sourceType: string,
  sourceId: string,
  userId?: string | null,
  reason?: string | null
) {
  const original = await tx.journalEntry.findUnique({
    where: {
      organizationId_sourceType_sourceId: { organizationId, sourceType, sourceId },
    },
    include: { lines: true, reversedByJournal: true },
  });
  if (!original) return null;
  if (original.status === JournalStatus.DRAFT) {
    await tx.journalLine.deleteMany({ where: { journalId: original.id } });
    await tx.journalAuditLog.deleteMany({ where: { journalId: original.id } });
    await tx.journalEntry.delete({ where: { id: original.id } });
    return { deletedDraft: true as const };
  }
  if (original.status === JournalStatus.REVERSED || original.reversedByJournal) {
    return { alreadyReversed: true as const, journal: original };
  }
  if (original.status !== JournalStatus.POSTED) {
    throw new AppError("Only posted journals can be reversed", 400);
  }

  const lines: JournalLineInput[] = original.lines.map((l) => ({
    accountId: l.accountId,
    debit: Number(l.credit),
    credit: Number(l.debit),
    memo: `Reversal of ${original.code}`,
  }));

  // Unique source key for reversal: append :REV
  const reversal = await createJournalInTx(tx, {
    organizationId,
    eventType: original.eventType,
    entryDate: new Date(),
    description: reason ?? `Reversal of ${original.code}`,
    sourceType: `${sourceType}:REV`,
    sourceId: sourceId,
    sourceCode: original.sourceCode,
    lines,
    autoGenerated: true,
    autoPost: true,
    userId,
    reversesJournalId: original.id,
  });

  await tx.journalEntry.update({
    where: { id: original.id },
    data: { status: JournalStatus.REVERSED },
  });
  await writeAudit(
    tx,
    organizationId,
    original.id,
    JournalAuditAction.REVERSED,
    userId,
    reason ?? `Reversed by ${reversal.code}`
  );

  return { reversal, original };
}

/** Soft-require accounting: if tenant has no rules at all, skip (accounting not seeded). If any rules exist, enforce. */
export async function generateForSourceIfAccountingEnabled(tx: Tx, ctx: SourcePostingContext) {
  const ruleCount = await tx.accountingPostingRule.count({
    where: { organizationId: ctx.organizationId },
  });
  if (ruleCount === 0) return null;
  return generateForSource(tx, ctx);
}

export async function reverseJournalForSourceIfExists(
  tx: Tx,
  organizationId: string,
  sourceType: string,
  sourceId: string,
  userId?: string | null,
  reason?: string | null
) {
  const ruleCount = await tx.accountingPostingRule.count({ where: { organizationId } });
  if (ruleCount === 0) return null;
  return reverseJournalForSource(tx, organizationId, sourceType, sourceId, userId, reason);
}
